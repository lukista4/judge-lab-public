"""Known-answer, position-swapped validity test for pairwise LLM judges (stdlib only).

A pairwise judge reads two versions of a text, A and B, and returns `overall` in 0..4 (4 = A clearly better, 2 = no clear
difference, 0 = B clearly better). Before such a judge is trusted on real comparisons, it is shown pairs whose answer is
known: an intact text against the same text with ONE planted, script-generated defect, each pair in both A/B orders.

Defect types (one pair per type per source text):
  a  drop      an interior step of the longest proof is removed
  b  flip      one non-strict inequality sign inside a stated result is reversed (<= <-> >=)
  c  swap      a stated result and the proof that follows it exchange places
  d  pad       neutral, mathematics-free filler is added until the text is about 10% longer (catches length bias)
  e  identical the same text twice (catches position bias)

Decision rule (stamped before any verdict is scored; thresholds for 6 source texts = 24 defect pairs, 6 padding pairs,
6 identical pairs):
  R1  the intact text wins >= 20 of the 24 defect pairs
  R2  the degraded text wins <= 2 of the 24
  R3  padding is caught (the unpadded text wins) in >= 4 of 6
  R4  no identical pair is won by the same copy in both orders
  R5  <= 15% of the defect pairs (<= 3) contradict themselves across the two orders
Pair classes from the favour f of the intact text in each order (f = score when intact is shown as A, 4 - score when it is
shown as B): AF both >= 3, LF one >= 3 and the other 2, T both 2, LS one <= 1 and the other 2, AS both <= 1,
C one >= 3 and the other <= 1. Default reading: "wins" = AF or LF.

Separation of the answer key: `build_study` returns a `manifest` (the key: pair id, defect type, which side is intact,
the exact edit) and a runner-facing `orders` list (order id, prompt, prompt sha256 only). `check_leakage` proves that no
order id, pair id or role word reaches a prompt and that every prompt is exactly the judge prefix plus the two texts.

The original study ran on course-text chapters that cannot be published. Here the source texts are generated by
`synthetic_chapter` (elementary inequalities written for this repository).
"""
import hashlib
import json
import random
import re

DEFECT_TYPES = ("a", "b", "c", "d")
ALL_TYPES = DEFECT_TYPES + ("e",)
TYPE_NAMES = {"a": "dropped proof step", "b": "flipped relation sign in a stated result",
              "c": "two adjacent sections swapped", "d": "about 10% neutral padding", "e": "identical copy"}
THRESHOLDS = dict(intact_wins_min=20, degraded_wins_max=2, padding_caught_min=4, identical_won_both_max=0,
                  contradiction_share_max=0.15)
ROLE_WORDS = ("intact", "variant", "degraded", "planted", "defect", "answer key")

JUDGE_PREFIX = ("You compare two versions, A and B, of the same mathematical text. Judge correctness, completeness and "
                "order of the argument. Reply with JSON {\"overall\": n} where n is 0..4: 4 = A clearly better, 3 = A "
                "somewhat better, 2 = no clear difference, 1 = B somewhat better, 0 = B clearly better.\n\n")

FILLER = [
    "This part continues the discussion in the same spirit.", "The reader may wish to pause here before going on.",
    "We keep the notation introduced above throughout.", "Nothing in what follows depends on the choice of labels.",
    "The same remarks apply, with obvious changes, to the next part.", "We return to this point later in the text.",
    "It is convenient to collect the facts used so far.", "The presentation follows the usual order of ideas.",
    "Some readers prefer to skip this paragraph on a first reading.", "The argument is short but worth reading slowly.",
    "We state things in the form that is easiest to quote.", "This finishes the preparatory remarks of the section.",
]


def sha256(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------------------------------- source texts
def synthetic_chapter(seed):
    """A short structured text: sections with kinds (definition, statement, proof). Returns list of sections
    dict(title, kind, body). Statements carry non-strict inequalities; proofs have >= 4 steps separated by blank lines."""
    rng = random.Random(seed)
    c = rng.randint(2, 9)
    k = rng.randint(3, 7)
    secs = [
        {"title": "Setting", "kind": "definition",
         "body": "Throughout, x_1, ..., x_n are real numbers and n >= %d. We write S = x_1 + ... + x_n." % (k - 1)},
        {"title": "Lemma 1", "kind": "statement",
         "body": "For all real a and b we have $|a + b| \\leq |a| + |b|$."},
        {"title": "Proof of Lemma 1", "kind": "proof",
         "body": ("Both sides are non-negative, so it suffices to compare squares.\n\n"
                  "We have $(a + b)^2 = a^2 + 2ab + b^2$.\n\n"
                  "Since $ab \\leq |a||b|$, we get $(a + b)^2 \\leq a^2 + 2|a||b| + b^2 = (|a| + |b|)^2$.\n\n"
                  "Taking square roots of non-negative quantities preserves the order, which gives the claim.")},
        {"title": "Lemma 2", "kind": "statement",
         "body": "For all real x_1, ..., x_n we have $|S| \\leq |x_1| + ... + |x_n|$."},
        {"title": "Proof of Lemma 2", "kind": "proof",
         "body": ("We argue by induction on n; for n = 1 there is nothing to prove.\n\n"
                  "Assume the claim for n - 1 numbers and put $T = x_1 + ... + x_{n-1}$.\n\n"
                  "By Lemma 1, $|T + x_n| \\leq |T| + |x_n|$.\n\n"
                  "By the induction hypothesis, $|T| \\leq |x_1| + ... + |x_{n-1}|$.\n\n"
                  "Adding $|x_n|$ to both sides and combining the two estimates proves the claim for n numbers.")},
        {"title": "Proposition 3", "kind": "statement",
         "body": "If $|x_i| \\leq %d$ for every i, then $|S| \\leq %d n$." % (c, c)},
        {"title": "Proof of Proposition 3", "kind": "proof",
         "body": ("By Lemma 2, $|S| \\leq |x_1| + ... + |x_n|$.\n\n"
                  "Each term on the right satisfies $|x_i| \\leq %d$.\n\n"
                  "There are n terms, so their sum is at most %d n.\n\n"
                  "Combining the two inequalities gives $|S| \\leq %d n$." % (c, c, c))},
        {"title": "Remarks", "kind": "remark",
         "body": "The constant %d cannot be lowered in general: take all x_i equal to %d." % (c, c)},
    ]
    return secs


def render(secs):
    return "".join("## %s\n\n%s\n\n" % (s["title"], s["body"]) for s in secs)


# ---------------------------------------------------------------------------------------------------- defect edits
def edit_drop(secs, rng):
    proofs = [i for i, s in enumerate(secs) if s["kind"] == "proof" and len(s["body"].split("\n\n")) >= 4]
    i = max(proofs, key=lambda j: len(secs[j]["body"]))
    steps = secs[i]["body"].split("\n\n")
    cands = [k for k in range(1, len(steps) - 1) if "\\leq" in steps[k] or "=" in steps[k]] or list(range(1, len(steps) - 1))
    k = cands[rng.randrange(len(cands))]
    new = [dict(s) for s in secs]
    new[i]["body"] = "\n\n".join(steps[:k] + steps[k + 1:])
    return new, {"operator": "drop_proof_step", "section": secs[i]["title"], "step": k + 1, "removed": steps[k]}


def edit_flip(secs, rng):
    cands = [(i, m.start()) for i, s in enumerate(secs) if s["kind"] == "statement"
             for m in re.finditer(r"\\(leq|geq)", s["body"])]
    i, p = cands[rng.randrange(len(cands))]
    body = secs[i]["body"]
    old = "\\leq" if body.startswith("\\leq", p) else "\\geq"
    newtok = "\\geq" if old == "\\leq" else "\\leq"
    new = [dict(s) for s in secs]
    new[i]["body"] = body[:p] + newtok + body[p + len(old):]
    return new, {"operator": "flip_relation_sign", "section": secs[i]["title"], "old": old, "new": newtok}


def edit_swap(secs, rng):
    cands = [i for i in range(len(secs) - 1) if secs[i]["kind"] == "statement" and secs[i + 1]["kind"] == "proof"]
    i = cands[rng.randrange(len(cands))]
    new = [dict(s) for s in secs]
    new[i], new[i + 1] = new[i + 1], new[i]
    return new, {"operator": "swap_adjacent_sections", "first": secs[i]["title"], "second": secs[i + 1]["title"]}


def edit_pad(secs, rng):
    target = 0.10 * len(render(secs))
    pool = list(FILLER)
    rng.shuffle(pool)
    new = [dict(s) for s in secs]
    eligible = list(range(1, len(secs) - 1))
    rng.shuffle(eligible)
    added, used, inserted = 0, 0, []
    for idx in eligible:
        if used + 2 > len(pool):
            break
        para = " ".join(pool[used:used + 2])
        if added + len(para) / 2.0 >= target:
            break
        new[idx]["body"] = new[idx]["body"] + "\n\n" + para
        added += len(para) + 2
        used += 2
        inserted.append(secs[idx]["title"])
    pct = 100.0 * (len(render(new)) - len(render(secs))) / len(render(secs))
    return new, {"operator": "pad_neutral_filler", "sections": inserted, "percent_added": round(pct, 2)}


EDITS = {"a": edit_drop, "b": edit_flip, "c": edit_swap, "d": edit_pad}


# ---------------------------------------------------------------------------------------------------- study build
def build_study(n_texts=6, seed=20261011):
    """Returns (manifest, orders). manifest = answer key; orders = runner input (no key fields)."""
    rng = random.Random(seed)
    pairs, orders_key = [], []
    for t in range(n_texts):
        secs = synthetic_chapter(seed * 100 + t)
        intact = render(secs)
        for typ in ALL_TYPES:
            pid = "P%02d" % (len(pairs) + 1)
            if typ == "e":
                variant, edit = intact, {"operator": "identical_copy"}
            else:
                vs, edit = EDITS[typ](secs, random.Random(sha256("%s|%s" % (seed, pid))))
                variant = render(vs)
                assert variant != intact
            pairs.append({"pair_id": pid, "text": t, "defect_type": typ, "intact": intact, "variant": variant, "edit": edit})
            first_a = rng.random() < 0.5
            for k, a_is_intact in ((1, first_a), (2, not first_a)):
                orders_key.append({"pair_id": pid, "order_in_pair": k, "shown_a": "intact" if a_is_intact else "variant"})
    rng.shuffle(orders_key)
    by_pid = {p["pair_id"]: p for p in pairs}
    orders = []
    for n, o in enumerate(orders_key, 1):
        o["order_id"] = "O%02d" % n
        p = by_pid[o["pair_id"]]
        a, b = (p["intact"], p["variant"]) if o["shown_a"] == "intact" else (p["variant"], p["intact"])
        prompt = assemble_prompt(a, b)
        o["prompt_sha256"] = sha256(prompt)
        orders.append({"order_id": o["order_id"], "prompt": prompt, "prompt_sha256": o["prompt_sha256"]})
    orders.sort(key=lambda o: o["order_id"])
    manifest = {"pairs": pairs, "orders": sorted(orders_key, key=lambda o: o["order_id"]), "seed": seed}
    return manifest, orders


def assemble_prompt(text_a, text_b):
    return JUDGE_PREFIX + "=== A ===\n" + text_a + "=== B ===\n" + text_b + "=== END ===\n"


def check_leakage(manifest, orders):
    """Returns a list of problems (empty = clean)."""
    bad = []
    by_pid = {p["pair_id"]: p for p in manifest["pairs"]}
    key = {o["order_id"]: o for o in manifest["orders"]}
    for o in orders:
        extra = set(o) - {"order_id", "prompt", "prompt_sha256"}
        if extra:
            bad.append((o["order_id"], "runner order carries key fields %s" % sorted(extra)))
        t = o["prompt"]
        k = key[o["order_id"]]
        for tok in (o["order_id"], k["pair_id"]):
            if re.search(r"(?<![A-Za-z0-9])%s(?![A-Za-z0-9])" % re.escape(tok), t):
                bad.append((o["order_id"], "id %s in prompt" % tok))
        low = t.lower()
        for w in ROLE_WORDS:
            if w in low:
                bad.append((o["order_id"], "role word %r in prompt" % w))
        p = by_pid[k["pair_id"]]
        a, b = (p["intact"], p["variant"]) if k["shown_a"] == "intact" else (p["variant"], p["intact"])
        if assemble_prompt(a, b) != t or sha256(t) != o["prompt_sha256"]:
            bad.append((o["order_id"], "prompt is not prefix + the two texts"))
    return bad


# ---------------------------------------------------------------------------------------------------- scoring
def favour_class(f1, f2):
    hi = [x >= 3 for x in (f1, f2)]
    lo = [x <= 1 for x in (f1, f2)]
    if all(hi):
        return "AF"
    if all(lo):
        return "AS"
    if any(hi) and any(lo):
        return "C"
    if any(hi):
        return "LF"
    if any(lo):
        return "LS"
    return "T"


def parse_verdict(text):
    """Strict JSON reply {"overall": 0..4}; a ```json fence is tolerated. Returns int or None."""
    t = (text or "").strip()
    m = re.match(r"^```(?:json)?\s*\n(.*)\n```\s*$", t, re.S)
    if m:
        t = m.group(1)
    try:
        v = json.loads(t)["overall"]
    except (ValueError, KeyError, TypeError):
        return None
    return v if isinstance(v, int) and not isinstance(v, bool) and 0 <= v <= 4 else None


def evaluate(manifest, verdicts, win_reading="lean"):
    """verdicts: {order_id: overall 0..4}. Returns per-pair rows."""
    by_pair = {}
    for o in manifest["orders"]:
        by_pair.setdefault(o["pair_id"], {})[o["order_in_pair"]] = o
    rows = []
    for p in manifest["pairs"]:
        o1, o2 = by_pair[p["pair_id"]][1], by_pair[p["pair_id"]][2]
        s1, s2 = verdicts.get(o1["order_id"]), verdicts.get(o2["order_id"])
        row = {"pair_id": p["pair_id"], "type": p["defect_type"], "outcome": "missing", "cls": None}
        if s1 is not None and s2 is not None:
            f1 = s1 if o1["shown_a"] == "intact" else 4 - s1
            f2 = s2 if o2["shown_a"] == "intact" else 4 - s2
            cls = favour_class(f1, f2)
            row.update(s1=s1, s2=s2, f1=f1, f2=f2, cls=cls)
            if p["defect_type"] != "e":
                won = cls in ("AF", "LF") if win_reading == "lean" else cls == "AF"
                lost = cls in ("AS", "LS") if win_reading == "lean" else cls == "AS"
                row["outcome"] = ("intact_wins" if won else "degraded_wins" if lost else
                                  "contradicted" if cls == "C" else "unresolved")
            else:
                row["outcome"] = "won_both_orders" if cls in ("AF", "AS") else ("contradicted" if cls == "C" else "tie_or_partial")
        rows.append(row)
    return rows


def summarize(rows, n_defect=24):
    defect = [r for r in rows if r["type"] != "e"]
    ident = [r for r in rows if r["type"] == "e"]
    pad = [r for r in rows if r["type"] == "d"]

    def cnt(rs, k):
        return sum(1 for r in rs if r["outcome"] == k)
    s = {"complete": all(r["outcome"] != "missing" for r in rows), "defect_pairs": len(defect),
         "intact_wins": cnt(defect, "intact_wins"), "degraded_wins": cnt(defect, "degraded_wins"),
         "unresolved": cnt(defect, "unresolved"), "contradicted": cnt(defect, "contradicted"),
         "padding_caught": cnt(pad, "intact_wins"), "identical_won_both": cnt(ident, "won_both_orders")}
    T = THRESHOLDS
    checks = [("R1", s["intact_wins"], s["intact_wins"] >= T["intact_wins_min"]),
              ("R2", s["degraded_wins"], s["degraded_wins"] <= T["degraded_wins_max"]),
              ("R3", s["padding_caught"], s["padding_caught"] >= T["padding_caught_min"]),
              ("R4", s["identical_won_both"], s["identical_won_both"] <= T["identical_won_both_max"]),
              ("R5", s["contradicted"], s["contradicted"] <= T["contradiction_share_max"] * n_defect + 1e-9)]
    s["checks"] = {k: {"value": v, "passed": bool(ok)} for k, v, ok in checks}
    if not s["complete"]:
        s["verdict"] = "INCOMPLETE"
    elif all(ok for _, _, ok in checks):
        s["verdict"] = "USABLE"
    else:
        s["verdict"] = "NOT USABLE"
    return s


def position_bias(verdicts):
    v = list(verdicts.values())
    a, b = sum(x >= 3 for x in v), sum(x <= 1 for x in v)
    return {"orders": len(v), "a_preferred": a, "b_preferred": b, "tie": len(v) - a - b,
            "share_a_among_decided": round(a / (a + b), 3) if a + b else None}


# ---------------------------------------------------------------------------------------------------- synthetic judges
def oracle_judge(manifest, strength=4):
    """Knows the key: prefers the intact text by `strength` (3 or 4), ties identical pairs."""
    pairs = {p["pair_id"]: p for p in manifest["pairs"]}
    out = {}
    for o in manifest["orders"]:
        if pairs[o["pair_id"]]["defect_type"] == "e":
            out[o["order_id"]] = 2
        else:
            out[o["order_id"]] = strength if o["shown_a"] == "intact" else 4 - strength
    return out


def position_judge(orders, prefer="A"):
    """Ignores content and always prefers the text shown first (or second)."""
    return {o["order_id"]: 4 if prefer == "A" else 0 for o in orders}


def length_judge(orders):
    """Reads only lengths: prefers the longer text (falls for padding)."""
    out = {}
    for o in orders:
        a = o["prompt"].split("=== A ===\n", 1)[1].split("=== B ===\n", 1)
        la, lb = len(a[0]), len(a[1].rsplit("=== END ===\n", 1)[0])
        out[o["order_id"]] = 3 if la > lb else (1 if lb > la else 2)
    return out
